export function getAnalyticsSeries(
  range: DateRangeKey,
  liveDeltaRevenue = 0,
  liveDeltaOrders = 0,
  locale: 'en' | 'zh' = 'en'
): {
  points: DailyMetricPoint[];
  deltas: { revenue: number; orders: number; aov: number; fulfillment: number };
} {
  const anchor = new Date('2026-11-18T12:00:00Z');
  const formatDayLabel = (d: Date) =>
    locale === 'zh'
      ? `${d.getUTCMonth() + 1}月${d.getUTCDate()}日`
      : d.toLocaleDateString('en-US', { month: 'short', day: 'numeric', timeZone: 'UTC' });

  if (range === '12m') {
    const points = BASELINE_12M.map((item, idx) => {
      const [yr, mo] = item.date.split('-');
      const zhLabel = `${yr.slice(2)}年${Number(mo)}月`;
      const localized = { ...item, label: locale === 'zh' ? zhLabel : item.label };
      return idx === BASELINE_12M.length - 1
        ? {
            ...localized,
            revenue: Math.max(0, Number((item.revenue + liveDeltaRevenue).toFixed(2))),
            orders: Math.max(0, item.orders + liveDeltaOrders),
          }
        : localized;
    });
    return {
      points,
      deltas: { revenue: 18.4, orders: 15.2, aov: 2.8, fulfillment: 1.4 },
    };
  }

  if (range === '90d') {
    // 13 weekly buckets ending Nov 18, 2026
    const weeklyRev = [
      19800, 20450, 21300, 20900, 22400, 23150, 22800, 24100, 24950, 23850, 25600, 26420, 27890,
    ];
    const weeklyOrd = [106, 109, 114, 111, 119, 123, 120, 127, 132, 126, 135, 139, 147];
    const points: DailyMetricPoint[] = weeklyRev.map((rev, idx) => {
      const d = new Date(anchor);
      d.setUTCDate(anchor.getUTCDate() - (weeklyRev.length - 1 - idx) * 7);
      const isLast = idx === weeklyRev.length - 1;
      return {
        date: d.toISOString().slice(0, 10),
        label: formatDayLabel(d),
        revenue: Math.max(0, Number((rev + (isLast ? liveDeltaRevenue : 0)).toFixed(2))),
        orders: Math.max(0, weeklyOrd[idx] + (isLast ? liveDeltaOrders : 0)),
        refunds: Math.round(rev * 0.022),
      };
    });
    return {
      points,
      deltas: { revenue: 14.6, orders: 11.9, aov: 2.4, fulfillment: 0.9 },
    };
  }

  const sliceLen = range === '7d' ? 7 : 30;
  const revSlice = BASELINE_30D_REVENUE.slice(-sliceLen);
  const ordSlice = BASELINE_30D_ORDERS.slice(-sliceLen);

  const points: DailyMetricPoint[] = revSlice.map((rev, idx) => {
    const d = new Date(anchor);
    d.setUTCDate(anchor.getUTCDate() - (sliceLen - 1 - idx));
    const isLast = idx === sliceLen - 1;
    return {
      date: d.toISOString().slice(0, 10),
      label: formatDayLabel(d),
      revenue: Math.max(0, Number((rev + (isLast ? liveDeltaRevenue : 0)).toFixed(2))),
      orders: Math.max(0, ordSlice[idx] + (isLast ? liveDeltaOrders : 0)),
      refunds: Math.round(rev * 0.024),
    };
  });

  return {
    points,
    deltas:
      range === '7d'
        ? { revenue: 12.8, orders: 9.6, aov: 2.9, fulfillment: 1.2 }
        : { revenue: 16.1, orders: 13.4, aov: 2.4, fulfillment: 1.1 },
  };
}
